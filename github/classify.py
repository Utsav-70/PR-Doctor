"""Per-file classification.

Two orthogonal axes, deliberately separate — conflating them is why "is this a test
file" becomes hard to answer later:

    language   how to parse it       python, yaml, dockerfile, binary, …
    category   what role it plays    source, test, dependency, documentation, config,
                                     generated

Everything here is table data rather than `if` chains, so adding a language is a
one-line change and the rules can be read without tracing control flow.

`reviewed` is computed separately from both axes: a file can be perfectly well
classified as `python`/`source` and still not be reviewed because it is deleted, or
oversized, or matched an ignore glob. Keeping that a third output rather than folding
it into `category` is what makes "which files did we actually look at, and why not the
others" answerable after the fact.
"""

