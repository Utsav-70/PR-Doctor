# Which roles are worth spending a review on. Changing this line changes what gets
# reviewed — it is the whole policy, in one place.
#
# `config` is excluded for now to preserve existing behaviour. Including it is the
# obvious next widening: a Dockerfile or a CI workflow is exactly where a
# privilege-escalation or secret-exposure bug hides, and PRGuard is blind to both today.
REVIEWABLE_CATEGORIES: frozenset[Category] = frozenset({"source", "test", "dependency"})


@dataclass(frozen=True, slots=True)
class FileClassification:
    language: Language
    category: Category
    reviewed: bool
    skip_reason: str | None = None


def _spec(patterns: tuple[str, ...] | list[str]) -> pathspec.PathSpec[pathspec.Pattern]:
    return pathspec.PathSpec.from_lines("gitwildmatch", patterns)


_GENERATED_SPEC = _spec(GENERATED_PATH_PATTERNS)
_TEST_SPEC = _spec(TEST_PATTERNS)


def matches_globs(path: str, globs: list[str]) -> bool:
    """gitignore-style path matching.

    Replaces fnmatch, which treats `**/migrations/**` as requiring a leading directory
    and therefore missed a top-level `migrations/`.
    """
    if not globs:
        return False
    return _spec(globs).match_file(path)


def looks_generated(content: str) -> bool:
    head = content[:_CONTENT_SNIFF_BYTES]
    return any(marker in head for marker in GENERATED_CONTENT_MARKERS)


def language_for(path: str) -> Language:
    name = posixpath.basename(path).lower()
    if name in FILENAME_LANGUAGE:
        return FILENAME_LANGUAGE[name]
    # `Dockerfile.prod`, `dockerfile.dev`
    if name.startswith("dockerfile"):
        return "dockerfile"
    # Manifests win over their own extension: package.json is a dependency file, not
    # "some JSON". Matches the worked example in phase-03-pr-analyzer.md.
    if name in DEPENDENCY_MANIFESTS or name.startswith(_DEPENDENCY_PREFIXES):
        return "dependency"
    _, _, ext = name.rpartition(".")
    suffix = f".{ext}" if ext and ext != name else ""
    if suffix in BINARY_EXTENSIONS:
        return "binary"
    return EXTENSION_LANGUAGE.get(suffix, "unknown")


def _category_for(path: str, language: Language, content: str | None) -> Category:
    """First match wins, in the order the spec lays out."""
    name = posixpath.basename(path).lower()

    if _GENERATED_SPEC.match_file(path):
        return "generated"
    if content is not None and looks_generated(content):
        return "generated"
    if _TEST_SPEC.match_file(path):
        return "test"
    if name in DEPENDENCY_MANIFESTS or name.startswith(_DEPENDENCY_PREFIXES):
        return "dependency"
    return LANGUAGE_CATEGORY.get(language, "source")


def classify(
    path: str,
    *,
    content: str | None = None,
    has_patch: bool = True,
    change_type: str = "modified",
    ignore_globs: list[str] | None = None,
) -> FileClassification:
    """Classify one changed file.

    `content` is optional — classification works from the path alone, and the content
    sniff only sharpens generated-file detection. That matters because classification
    runs before we decide which files are worth fetching.
    """
    language = language_for(path)
    category = _category_for(path, language, content)

    # Disqualifiers, most specific first. The first one that fires is the reason
    # recorded, so "why wasn't this reviewed" has a single unambiguous answer.
    reason: str | None = None
    if change_type == "removed":
        reason = "deleted"
    elif ignore_globs and matches_globs(path, ignore_globs):
        reason = "ignored_path"
    elif language == "binary":
        # Checked before `generated` because it is the more informative answer: a .png
        # is categorised `generated` only as a fallback.
        reason = "binary"
    elif category == "generated":
        reason = "generated"
    elif not has_patch:
        # Binary, oversized, or a mode-only change — GitHub omits the patch for all
        # three and does not say which.
        reason = "no_patch"
    elif category not in REVIEWABLE_CATEGORIES:
        reason = f"category_{category}"

    return FileClassification(
        language=language,
        category=category,
        reviewed=reason is None,
        skip_reason=reason,
    )
